const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const sandbox = {URL};
sandbox.globalThis = sandbox;
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../js/content/academy-resource-import-validation.js'),'utf8'),sandbox);
const {validate,validateBatch}=sandbox.SpeakOutAcademyImport;
const register=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/academy-source-resources.json'),'utf8'));
const results=validateBatch(register.resources);
assert.ok(results.length>=13,'Source register must retain its established records');
for(const result of results)assert.equal(result.valid,true,'Invalid source record '+result.id+': '+result.errors.join('; '));
const sample={...register.resources[0]};
assert.equal(validate({...sample,url:'https://example.com/topics/851'}).valid,false,'Must reject mismatched source domains');
assert.equal(validate({...sample,url:'http://ignite.education.gov.ng/topics/851'}).valid,false,'Must require HTTPS');
assert.equal(validate({...sample,publicationStatus:'native-published'}).valid,false,'Must block unapproved native publication');
assert.equal(validate({...sample,publicationStatus:'native-published',rightsStatus:'cleared',reviewStatus:'approved',sourceVerifiedAt:'2026-10-12',assetUrl:'https://example.org/file.pdf',approvedBy:'Reviewer'}).valid,true,'Fully reviewed publication should pass');
assert.equal(validateBatch([sample,sample])[1].valid,false,'Must reject duplicate IDs');
console.log('Academy partner resource register and publication gates validated:',results.length,'records');
