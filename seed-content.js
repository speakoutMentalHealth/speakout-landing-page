async function isAdmin(user){
  if(!user) return false;
  const snap = await getDoc(doc(db, "users", user.uid));
  if(!snap.exists()) return false;
  const profile = snap.data();
  return profile.role === "admin" && profile.status === "approved";
}

async function seedCollection(collectionName, rows, keyField){
  const existing = await getDocs(collection(db, collectionName));
  const existingKeys = new Set();
  existing.forEach(item => {
    const data = item.data();
    if(data[keyField]) existingKeys.add(data[keyField].toLowerCase());
  });

  const batch = writeBatch(db);
  let count = 0;

  rows.forEach(row => {
    const key = String(row[keyField] || "").toLowerCase();
    if(!key || existingKeys.has(key)) return;

    const ref = doc(collection(db, collectionName));
    batch.set(ref, {
      ...row,
      createdAt: serverTimestamp(),
      updatedAt: serverTimestamp()
    });
    count++;
  });

  if(count > 0) await batch.commit();
  return count;
}

export async function seedSpeakOutContent(){
  const user = auth.currentUser;
  if(!await isAdmin(user)){
    throw new Error("Only approved admins can seed content.");
  }

  const booksAdded = await seedCollection("books", PRELOADED_BOOKS, "title");
  const coursesAdded = await seedCollection("courses", PRELOADED_COURSES, "title");
  const kiddiesAdded = await seedCollection("kiddiesResources", PRELOADED_KIDDIES, "title");

  return { booksAdded, coursesAdded, kiddiesAdded };
}

window.seedSpeakOutContent = seedSpeakOutContent;

onAuthStateChanged(auth, async user => {
  const status = document.getElementById("seedStatus");
  const button = document.getElementById("seedButton");

  if(!status || !button) return;

  if(!user){
    status.textContent = "Login as admin first.";
    button.disabled = true;
    return;
  }

  if(!await isAdmin(user)){
    status.textContent = "You are logged in, but this page is admin-only.";
    button.disabled = true;
    return;
  }

  status.textContent = "Admin verified. You can seed starter content.";
  button.disabled = false;
});
